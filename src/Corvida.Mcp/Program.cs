using Corvida.Mcp;
using Corvida.Services;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;

var builder = Host.CreateApplicationBuilder(args);

// Logging must go to stderr — stdout is reserved for MCP JSON-RPC messages
builder.Logging.AddConsole(o => o.LogToStandardErrorThreshold = LogLevel.Trace);
builder.Logging.SetMinimumLevel(LogLevel.Warning);

builder.Services.AddSingleton<ISettingsService, SettingsService>();

builder.Services.AddSingleton<BoardService>();
builder.Services.AddSingleton<HttpBoardService>();
builder.Services.AddSingleton<IBoardService, StorageAwareBoardService>();

builder.Services.AddSingleton<TaskService>();
builder.Services.AddSingleton<HttpTaskService>();
builder.Services.AddSingleton<ITaskService, StorageAwareTaskService>();

builder.Services.AddSingleton<AgentService>();
builder.Services.AddSingleton<HttpAgentService>();
builder.Services.AddSingleton<IAgentService, StorageAwareAgentService>();

// The MCP server cannot prompt for credentials, so it authenticates with a personal access token
// from settings.json — the same file the desktop app writes, generated by an administrator there.
builder.Services.AddSingleton<ITokenProvider, ApiKeyTokenProvider>();
builder.Services.AddTransient<AuthMessageHandler>();
builder.Services.AddHttpClient("CorvidaApi").AddHttpMessageHandler<AuthMessageHandler>();
builder.Services.AddHostedService<SettingsLoader>();

builder.Services
    .AddMcpServer()
    .WithStdioServerTransport()
    .WithToolsFromAssembly();

await builder.Build().RunAsync();
